#include <iostream>
using namespace std;

int main() {
    // cout sends text to the terminal.
    // In Python, this is similar to print().
    // In JavaScript, it is similar to console.log().
    cout << "Hello, World!" << endl;

    // 0 means the program ended successfully.
    return 0;
}
