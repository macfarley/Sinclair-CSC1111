// Template-notes.cpp
// This is the notes-style boilerplate starter for a C++ assignment.
// It is meant to be easy to reuse and explain while still being executable.

#include <iostream>
using namespace std;

int main() {
    // Variables are like labeled boxes that store values.
    string name = "Your Name";
    string major = "Your Major";
    int credits = 0;
    string reflection = "This course will help me by...";

    // cout is the console output stream.
    cout << "Name: " << name << endl;
    cout << "Major: " << major << endl;
    cout << "Credits this term: " << credits << endl;
    cout << "How this course helps my goals: " << reflection << endl;

    // A successful program ends with return 0.
    return 0;
}
